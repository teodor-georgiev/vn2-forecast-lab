"""Fit the per-series config selection once (offline) and emit policy_params.py."""

from __future__ import annotations

import numpy as np

import tune as T
import tune2 as T2

Y, YC, INIT = T.Y, T.YC, T.INIT
N = Y.shape[0]
H = Y

tune_windows = [95, 105, 115, 125, 130, 145]

tot_tune, per_tune = T2.evaluate(T2.CONFIGS, tune_windows, None)
mean_tune = tot_tune.mean(1)
order = list(np.argsort(mean_tune)[:8])

# per-series selection among the top-8 global configs
per_tune_sum = per_tune[order].sum(1)  # (K, n)
sel_k = np.argmin(per_tune_sum, axis=0)  # index into order
sel_cfg = [T2.CONFIGS[order[k]] for k in sel_k]

ps_tune = np.array(
    [per_tune[order[sel_k[i]], :, i].sum() for i in range(N)]
).mean() / len(tune_windows)
best_global = float(mean_tune[order[0]])
print("tune windows", tune_windows)
print("reference:", end=" ")
tot_ref, _ = T2.evaluate(
    [dict(scale=1.0, buffer=0.75, projection=1.0, base="raw", adapt=0.0, trend=False)],
    tune_windows,
    None,
)
print(round(float(tot_ref.mean()), 1))
print("best global:", round(best_global, 1))
print("per-series :", round(float(ps_tune), 1))

# holdout validation
hold_windows = [100, 120, 140, 149]
top_idx = order
tot_hold, per_hold = T2.evaluate([T2.CONFIGS[i] for i in top_idx], hold_windows, None)
tot_ref_h, _ = T2.evaluate(
    [dict(scale=1.0, buffer=0.75, projection=1.0, base="raw", adapt=0.0, trend=False)],
    hold_windows,
    None,
)
ps_hold = np.array([per_hold[sel_k[i], :, i].sum() for i in range(N)]).mean() / len(
    hold_windows
)
print("holdout windows", hold_windows)
print("reference :", round(float(tot_ref_h.mean()), 1))
print("best glob :", round(float(tot_hold.min(1).mean()), 1))
print("per-series:", round(float(ps_hold), 1))

# write the params file consumed by policy.py
uniq = {}
flat = np.zeros(N, dtype=int)
for i, cfg in enumerate(sel_cfg):
    key = tuple(sorted(cfg.items()))
    if key not in uniq:
        uniq[key] = (len(uniq), cfg)
    flat[i] = uniq[key][0]
blocks = [cfg for _, cfg in sorted(uniq.values(), key=lambda x: x[0])]

lines = [
    "# Auto-generated by fit_params.py - per-series deficit-rule parameters.",
    "# Row order matches the sorted series_id order of the arena data files.",
    "BLOCKS = [",
]
for cfg in blocks:
    lines.append(
        "    dict(scale=%r, buffer=%r, projection=%r, base=%r, adapt=%r, trend=%r),"
        % (
            cfg["scale"],
            cfg["buffer"],
            cfg["projection"],
            cfg["base"],
            cfg["adapt"],
            bool(cfg["trend"]),
        )
    )
lines.append("]")
lines.append("SERIES_BLOCK = np.array(%s, dtype=int)" % flat.tolist())
lines.append("")
open("policy_params.py", "w").write("\n".join(lines))
print("distinct blocks:", len(blocks), "-> policy_params.py written")
vals, cnts = np.unique(flat, return_counts=True)
print(
    "mix:",
    [
        (blocks[v]["base"], blocks[v]["scale"], blocks[v]["adapt"], int(c))
        for v, c in zip(vals, cnts)
    ],
)
